/**
 * Новостная лента под клиента.
 *
 * В требованиях кейса: «при демонстрации покажите, как изменяется новостная лента
 * под клиента, что содержится в новостях». Ни бэкенда, ни договорённости о том,
 * откуда берутся новости и по какому признаку персонализируются, пока нет.
 *
 * Тексты ниже — рыба, чтобы было видно место на экране и состав карточки.
 */

type Props = {
  /** По ОКВЭД и статусу заявки лента и должна меняться — отсюда и «под клиента». */
  okvedName?: string | null;
  statusTitle?: string;
};

export default function NewsFeed({ okvedName, statusTitle }: Props) {
  const items = [
    {
      tag: "по вашей отрасли",
      title: okvedName
        ? `Что меняется для «${okvedName}» в этом квартале`
        : "Новость по отрасли клиента",
      why: "подбирается по ОКВЭД компании",
    },
    {
      tag: "по вашей заявке",
      title: statusTitle
        ? `Пока заявка в статусе «${statusTitle}»: что можно подготовить заранее`
        : "Новость по текущему статусу заявки",
      why: "подбирается по статусу заявки",
    },
    {
      tag: "продукты банка",
      title: "Ставка по оборотному кредиту изменилась",
      why: "общая для всех, без персонализации",
    },
  ];

  return (
    <section className="stub" data-why="лента не реализована, тексты выдуманы">
      <h3>Новости для вас</h3>
      <table>
        <thead>
          <tr>
            <th>Метка</th>
            <th>Заголовок</th>
            <th>Чем персонализируется</th>
          </tr>
        </thead>
        <tbody>
          {items.map((n) => (
            <tr key={n.tag}>
              <td>{n.tag}</td>
              <td>{n.title}</td>
              <td className="muted">{n.why}</td>
            </tr>
          ))}
        </tbody>
      </table>
      <p className="muted">
        Надо решить: источник новостей, правила подбора и нужен ли эндпоинт{" "}
        <code>GET /api/news?inn=</code>.
      </p>
    </section>
  );
}
